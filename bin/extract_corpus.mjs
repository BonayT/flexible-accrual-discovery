// Turns the prompt library into the simulator's shortcut list.
//
//   node bin/extract_corpus.mjs ~/Downloads/one-accrual-prompts.html > docs/prompts.js
//
// Every prompt is reproduced verbatim in the client's own language, because the
// point of the corpus is that these are the words people actually typed. The
// outcome and route come from the entry's own data attributes, so a re-export of
// the library updates them without anyone re-reading a screenshot.

import { readFileSync } from 'node:fs';

const html = readFileSync(process.argv[2], 'utf8');

const decode = (s) =>
  s
    .replace(/<[^>]*>/g, '')
    .replace(/&nbsp;/g, ' ')
    .replace(/&amp;/g, '&')
    .replace(/&lt;/g, '<')
    .replace(/&gt;/g, '>')
    .replace(/&quot;/g, '"')
    .replace(/&#39;/g, "'")
    .replace(/&ldquo;|&rdquo;/g, '"')
    .replace(/\s+/g, ' ')
    .trim();

// Section headings carry the rule family each group of entries targets.
const families = [];
for (const match of html.matchAll(/<h2[^>]*>([^<]+)<\/h2>/g)) families.push({ index: match.index, name: decode(match[1]) });
const familyAt = (index) => {
  let current = null;
  for (const f of families) if (f.index < index) current = f.name;
  return current;
};

// Left out on purpose: that section collects asks about One as a product —
// where its suggestions come from, whether it learns, what it should say it
// cannot do. None of them is a rule, so the simulator has nothing to answer.
const EXCLUDED_FAMILIES = ['Requests about One itself'];

const entries = [];
const entryRe = /<div class="entry"([^>]*)>([\s\S]*?)<div class="meta">([\s\S]*?)<\/div>/g;

for (const match of html.matchAll(entryRe)) {
  const [, attrs, body, meta] = match;
  const said = body.match(/<p class="said">([\s\S]*?)<\/p>/);
  if (!said) continue;

  const outcome = (attrs.match(/data-out="([^"]+)"/) || [])[1] || null;
  const route = (attrs.match(/data-src="([^"]+)"/) || [])[1] || null;
  const replies = [...body.matchAll(/<p class="reply">([\s\S]*?)<\/p>/g)].map((m) => decode(m[1]));
  const chips = [...meta.matchAll(/<span class="chip[^"]*">([^<]*)<\/span>/g)].map((m) => decode(m[1]));
  const market = chips.find((c) => /^[A-Z]{2}$/.test(c)) || null;
  const source = decode((meta.match(/<span class="src-line">([\s\S]*?)<\/span>/) || [])[1] || '');

  if (EXCLUDED_FAMILIES.includes(familyAt(match.index))) continue;

  entries.push({
    text: decode(said[1]),
    reply: replies.join(' ') || null,
    outcome,
    route,
    market,
    source,
    family: familyAt(match.index)
  });
}

const counts = entries.reduce((acc, e) => ({ ...acc, [e.outcome]: (acc[e.outcome] || 0) + 1 }), {});
process.stderr.write(`${entries.length} prompts, por resultado: ${JSON.stringify(counts)}\n`);

console.log(`// Generated by bin/extract_corpus.mjs from the One Accrual Prompt Library.
// Every line is a client's own words, reproduced verbatim. Do not edit by hand:
// re-run the script against a fresh export instead.

export const PROMPTS = ${JSON.stringify(entries, null, 2)};
`);
